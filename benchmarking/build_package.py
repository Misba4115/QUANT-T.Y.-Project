"""Build the six QUANT deliverables from the generator's rows and run quality checks.
Usage: python build_package.py <rows.json> <outdir>
"""
from __future__ import annotations

import csv
import json
import re
import statistics
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

rows_path, out = Path(sys.argv[1]), Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
R = json.loads(rows_path.read_text())
for r in R:
    r["dt"] = datetime.fromisoformat(r["when"])

CATEGORIES = {"Food & Dining", "Groceries", "Transport", "Shopping", "Utilities", "Entertainment", "Healthcare",
              "Investment", "Rent", "Salary/Income", "Transfer", "Other", "EMI"}
ANOM = {"amount_spike", "duplicate_transaction", "large_round_transfer", "odd_hour", "unusual_category_first_seen", "other_confirmed"}
PII = {
    "email": re.compile(r"\b[^\s@]+@[^\s@]+\.[^\s@]+\b", re.I),
    "upi_handle": re.compile(r"\b[a-z0-9._-]{2,}@[a-z][a-z0-9.-]{1,}\b", re.I),
    "phone": re.compile(r"(?<!\d)(?:\+?91[- ]?)?[6-9]\d{9}(?!\d)"),
    "pan": re.compile(r"\b[A-Z]{5}\d{4}[A-Z]\b", re.I),
    "long_number": re.compile(r"(?<!\d)\d{10,18}(?!\d)"),
}
TEMPLATE_FIELDS = ["record_id", "account_id", "tx_date", "occurred_at", "description", "amount", "tx_type", "expected_category",
                   "is_anomaly", "anomaly_type", "label_confidence", "reviewer_id", "reviewer_independent", "adjudication_status",
                   "consent_confirmed", "data_origin"]
PROV = "SYNTHETIC: generated by generate_quant_candidate.py (seed 20261008); no source records copied from any third-party dataset"

def prio(r):
    if r["is_anomaly"] == "true" or r["scenario"].startswith("decoy") or r["scenario"].startswith("duplicate") or r["conf"] == "low":
        return "high"
    return "medium" if (r["conf"] == "medium" or r["review"] == "yes") else "standard"

def fmt(r):
    return f"{r['amount']:.2f}"

# ---------------- candidate
cand_fields = ["record_id", "account_id", "tx_date", "occurred_at", "description", "amount", "tx_type", "expected_category",
               "is_anomaly", "anomaly_type", "label_confidence", "category_label_source", "anomaly_label_source", "scenario_id",
               "data_origin", "provenance", "reasoning_notes", "needs_human_review", "review_priority"]
with (out / "quant_candidate_dataset.csv").open("w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, cand_fields, lineterminator="\n"); w.writeheader()
    for r in R:
        w.writerow(dict(record_id=r["record_id"], account_id=r["account_id"], tx_date=r["tx_date"], occurred_at=r["occurred_at"],
                        description=r["description"], amount=fmt(r), tx_type=r["tx_type"], expected_category=r["expected_category"],
                        is_anomaly=r["is_anomaly"], anomaly_type=r["anomaly_type"], label_confidence=r["conf"],
                        category_label_source=r["cat_source"], anomaly_label_source=r["anom_source"], scenario_id=r["scenario"],
                        data_origin="synthetic", provenance=PROV, reasoning_notes=r["notes"],
                        needs_human_review="true" if r["review"] == "yes" else "false", review_priority=prio(r)))

# ---------------- human review
rev_fields = ["record_id", "account_id", "tx_date", "occurred_at", "description", "amount", "tx_type", "proposed_category",
              "proposed_is_anomaly", "proposed_anomaly_type", "data_origin", "data_source_provenance", "label_confidence",
              "ai_reasoning_notes", "review_priority", "human_category", "human_is_anomaly", "human_anomaly_type",
              "reviewer_comments", "review_status", "reviewer_id"]
with (out / "quant_human_review.csv").open("w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, rev_fields, lineterminator="\n"); w.writeheader()
    for r in R:
        w.writerow(dict(record_id=r["record_id"], account_id=r["account_id"], tx_date=r["tx_date"], occurred_at=r["occurred_at"],
                        description=r["description"], amount=fmt(r), tx_type=r["tx_type"], proposed_category=r["expected_category"],
                        proposed_is_anomaly=r["is_anomaly"], proposed_anomaly_type=r["anomaly_type"], data_origin="synthetic",
                        data_source_provenance="synthetic generator; AI/scenario-proposed labels; NOT human verified",
                        label_confidence=r["conf"], ai_reasoning_notes=r["notes"], review_priority=prio(r),
                        human_category="", human_is_anomaly="", human_anomaly_type="", reviewer_comments="",
                        review_status="pending", reviewer_id=""))

# ---------------- holdout-ready draft
with (out / "quant_holdout_ready.csv").open("w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, TEMPLATE_FIELDS, lineterminator="\n"); w.writeheader()
    for r in R:
        w.writerow(dict(record_id=r["record_id"], account_id=r["account_id"], tx_date=r["tx_date"], occurred_at=r["occurred_at"],
                        description=r["description"], amount=fmt(r), tx_type=r["tx_type"], expected_category=r["expected_category"],
                        is_anomaly=r["is_anomaly"], anomaly_type=r["anomaly_type"], label_confidence=r["conf"],
                        reviewer_id="reviewer_PENDING", reviewer_independent="false", adjudication_status="single_review",
                        consent_confirmed="false", data_origin="synthetic"))

# ---------------- quality checks (mirror prepare_holdout.py rules; dev-set overlap NOT checkable here)
err, warn = [], []
ids = set()
cat_c, anom_c, acct_c = Counter(), Counter(), Counter()
missing = Counter()
with (out / "quant_holdout_ready.csv").open(newline="", encoding="utf-8") as f:
    H = list(csv.DictReader(f))
assert list(H[0].keys()) == TEMPLATE_FIELDS
for n, row in enumerate(H, start=2):
    for k, v in row.items():
        if v == "" and k != "anomaly_type":
            missing[k] += 1
    if row["record_id"] in ids: err.append(f"dup id {row['record_id']}")
    ids.add(row["record_id"])
    if not re.fullmatch(r"acct_[A-Za-z0-9_-]+", row["account_id"]): err.append(f"{n} acct")
    datetime.strptime(row["tx_date"], "%Y-%m-%d")
    pt = datetime.fromisoformat(row["occurred_at"].replace("Z", "+00:00"))
    if pt.utcoffset() is None: err.append(f"{n} tz")
    if row["tx_date"] != pt.strftime("%Y-%m-%d"): err.append(f"{n} date/time mismatch")
    if float(row["amount"]) <= 0: err.append(f"{n} amount")
    if row["tx_type"] not in {"debit", "credit"}: err.append(f"{n} txtype")
    if row["expected_category"] not in CATEGORIES: err.append(f"{n} cat")
    cat_c[row["expected_category"]] += 1
    isa = row["is_anomaly"] == "true"
    if isa and row["anomaly_type"] not in ANOM: err.append(f"{n} anomtype")
    if (not isa) and row["anomaly_type"]: err.append(f"{n} normal with type")
    if isa: anom_c[row["anomaly_type"]] += 1
    if row["label_confidence"] not in {"high", "medium", "low"}: err.append(f"{n} conf")
    for nm, pat in PII.items():
        if pat.search(row["description"]): err.append(f"{n} PII {nm}")
    acct_c[row["account_id"]] += 1
structural_errors = err

# scenario-consistency re-verification from the emitted data (independent of generator internals)
by_acct = defaultdict(list)
for row in H:
    row["dt"] = datetime.fromisoformat(row["occurred_at"]); row["amt"] = float(row["amount"])
    by_acct[row["account_id"]].append(row)
for a in by_acct: by_acct[a].sort(key=lambda x: x["dt"])
consistency = []
for a, rs in by_acct.items():
    for i, row in enumerate(rs):
        t = row["anomaly_type"]
        prior = rs[:i]
        if t == "odd_hour" and not (1 <= row["dt"].hour <= 4): consistency.append((row["record_id"], "odd_hour outside 01-04:59"))
        if t == "large_round_transfer":
            if not (row["amt"] >= 50000 and row["amt"] % 5000 == 0): consistency.append((row["record_id"], "round rule"))
            payee = row["description"]
            nm = re.sub(r"^(UPI/P2A/\d+/|IMPS-\d+-|NEFT-\d+-)", "", payee)
            if any(nm in p["description"] for p in prior): consistency.append((row["record_id"], "payee seen before"))
        if t == "duplicate_transaction":
            m = [p for p in prior if p["description"] == row["description"] and p["amt"] == row["amt"] and 0 < (row["dt"] - p["dt"]).total_seconds() <= 180]
            if not m: consistency.append((row["record_id"], "no original within 180s"))
        if t == "unusual_category_first_seen":
            if any(p["expected_category"] == row["expected_category"] for p in prior): consistency.append((row["record_id"], "category seen before"))
            meddeb = statistics.median(p["amt"] for p in rs if p["tx_type"] == "debit")
            if row["amt"] < 5 * meddeb: consistency.append((row["record_id"], "<5x median debit"))
        if t == "amount_spike":
            same = [p["amt"] for p in rs if p["expected_category"] == row["expected_category"] and p["tx_type"] == "debit" and p["is_anomaly"] == "false" and not p["description"].startswith("REFUND")]
            if row["amt"] < 9 * statistics.median(same) or row["amt"] < 5000: consistency.append((row["record_id"], f"spike ratio {row['amt']/statistics.median(same):.1f}"))

exact_desc = Counter(re.sub(r"[^a-z0-9]+", " ", r["description"].casefold()).strip() for r in H)
dup_desc = {d: c for d, c in exact_desc.items() if c > 1}
pii_free = not any("PII" in e for e in err)
merchants = {r["merchant"] for r in R}
templates = {re.sub(r"\d+", "#", r["description"]) for r in R}
amt_by_type = defaultdict(list)
for r in R: amt_by_type[r["tx_type"]].append(r["amount"])
n = len(H); n_anom = sum(anom_c.values())
rows_per_acct = dict(sorted(acct_c.items()))
review_counts = Counter(prio(r) for r in R)
conf_counts = Counter(r["conf"] for r in R)
scen = Counter(r["scenario"] for r in R)
dates = sorted(r["tx_date"] for r in R)
hours_night = sum(1 for r in R if r["dt"].hour in (23, 0))

# per-account anomaly counts
per_acct_anom = Counter(r["account_id"] for r in R if r["is_anomaly"] == "true")
no_anom_accts = [a for a in rows_per_acct if per_acct_anom[a] == 0]
stats = dict(n=n, n_anom=n_anom, anom=dict(anom_c), cats=dict(cat_c), accts=rows_per_acct, structural_errors=structural_errors,
             consistency=consistency, dup_desc=dup_desc, missing=dict(missing), review=dict(review_counts), conf=dict(conf_counts),
             scen=dict(scen), n_merchants=len(merchants), n_templates=len(templates), dates=[dates[0], dates[-1]],
             amount_min=min(r["amount"] for r in R), amount_max=max(r["amount"] for r in R),
             amount_median_debit=statistics.median(amt_by_type["debit"]), credits=len(amt_by_type["credit"]),
             no_anom_accts=no_anom_accts, per_acct_anom=dict(per_acct_anom), pii_free=pii_free)
(out / "_stats.json").write_text(json.dumps(stats, indent=1, default=str))
print(json.dumps({k: stats[k] for k in ("n", "n_anom", "anom", "structural_errors", "consistency", "review", "conf", "n_merchants", "n_templates", "no_anom_accts")}, indent=1))
print("dup desc groups:", len(dup_desc), sum(dup_desc.values()))
print("category <20:", [c for c, v in cat_c.items() if v < 20], "accounts<20:", [a for a, v in acct_c.items() if v < 20])
